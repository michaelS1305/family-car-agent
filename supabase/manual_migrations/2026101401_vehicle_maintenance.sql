-- 1. Read-only preflight. Existing object must be NULL.
SELECT current_database() AS database_name, current_user AS execution_role;
SELECT to_regclass('public.vehicle_maintenance') AS existing_object;
SELECT c.relname, a.attname, format_type(a.atttypid,a.atttypmod) AS data_type
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
JOIN pg_attribute a ON a.attrelid=c.oid
WHERE n.nspname='public' AND c.relname IN ('vehicles','users')
  AND a.attname='id' AND NOT a.attisdropped;

-- 2. Additive DDL; fail closed on a conflicting/previous application.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
DO $preflight$
BEGIN
    IF current_user <> 'postgres'
       OR (SELECT count(*) FROM pg_roles WHERE rolname IN ('anon','authenticated','service_role')) <> 3
       OR to_regclass('public.vehicle_maintenance') IS NOT NULL THEN
        RAISE EXCEPTION 'Unexpected executor, roles or existing maintenance table';
    END IF;
    IF (SELECT count(*) FROM pg_attribute a JOIN pg_constraint c
          ON c.conrelid=a.attrelid AND c.contype='p' AND c.conkey=ARRAY[a.attnum]
        WHERE a.attrelid IN (to_regclass('public.vehicles'),to_regclass('public.users'))
          AND a.attname='id' AND a.atttypid='integer'::regtype
          AND a.attnotnull AND NOT a.attisdropped) <> 2 THEN
        RAISE EXCEPTION 'Expected vehicle/user integer primary keys missing';
    END IF;
END
$preflight$;

CREATE TABLE public.vehicle_maintenance (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    maintenance_ref uuid NOT NULL DEFAULT gen_random_uuid(),
    vehicle_id integer NOT NULL REFERENCES public.vehicles(id) ON DELETE CASCADE,
    description text NOT NULL,
    scheduled_date date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by_user_id integer REFERENCES public.users(id) ON DELETE SET NULL,
    CONSTRAINT vehicle_maintenance_pkey PRIMARY KEY (id),
    CONSTRAINT vehicle_maintenance_ref_key UNIQUE (maintenance_ref),
    CONSTRAINT vehicle_maintenance_description_check CHECK (description !~ '^[[:space:]]*$'),
    CONSTRAINT vehicle_maintenance_date_check CHECK (isfinite(scheduled_date)),
    CONSTRAINT vehicle_maintenance_created_at_check CHECK (isfinite(created_at))
);
CREATE INDEX vehicle_maintenance_vehicle_date_idx
    ON public.vehicle_maintenance(vehicle_id,scheduled_date,id);
-- Soft retirement never deletes the vehicle, so all maintenance is preserved.
-- Account deletion may null attribution; existing physical vehicle/family cleanup cascades.
ALTER TABLE public.vehicle_maintenance OWNER TO postgres;
ALTER TABLE public.vehicle_maintenance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vehicle_maintenance NO FORCE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.vehicle_maintenance FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL PRIVILEGES (id,maintenance_ref,vehicle_id,description,scheduled_date,created_at,created_by_user_id)
    ON TABLE public.vehicle_maintenance FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE, REFERENCES, TRIGGER, TRUNCATE
    ON TABLE public.vehicle_maintenance TO service_role;
REVOKE ALL PRIVILEGES ON SEQUENCE public.vehicle_maintenance_id_seq FROM PUBLIC, anon, authenticated, service_role;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.vehicle_maintenance_id_seq TO service_role;
COMMIT;

