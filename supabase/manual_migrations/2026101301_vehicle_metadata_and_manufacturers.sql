-- 2. ADDITIVE DDL. One transaction includes DDL, ACL and seed.
-- Not blindly rerunnable: unexpected/pre-existing objects fail closed.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
DO $preflight$
BEGIN
    IF current_user <> 'postgres'
       OR (SELECT count(*) FROM pg_roles WHERE rolname IN
           ('anon','authenticated','service_role')) <> 3
       OR to_regclass('public.vehicles') IS NULL THEN
        RAISE EXCEPTION 'Unexpected executor, roles or missing vehicles table';
    END IF;
    IF EXISTS (SELECT FROM (VALUES ('vehicle_manufacturers'),('vehicle_manufacturers_id_seq'),
               ('vehicle_manufacturers_pkey'),('vehicle_manufacturers_name_he_key')) AS n(name)
               WHERE to_regclass('public.' || name) IS NOT NULL)
       OR to_regtype('public.vehicle_manufacturers') IS NOT NULL
       OR EXISTS (SELECT FROM pg_attribute WHERE attrelid='public.vehicles'::regclass
                  AND NOT attisdropped AND attname IN
                  ('category','manufacturer_id','model','license_plate'))
       OR EXISTS (SELECT FROM pg_constraint WHERE conrelid='public.vehicles'::regclass
                  AND conname IN ('vehicles_category_check','vehicles_model_check',
                                  'vehicles_license_plate_check','vehicles_manufacturer_id_fkey')) THEN
        RAISE EXCEPTION 'Already applied or conflicting vehicle metadata objects';
    END IF;
    IF NOT EXISTS (
        SELECT FROM pg_attribute a JOIN pg_constraint c
          ON c.conrelid=a.attrelid AND c.contype='p' AND c.conkey=ARRAY[a.attnum]
        WHERE a.attrelid='public.vehicles'::regclass AND a.attname='id'
          AND a.atttypid='integer'::regtype AND a.attnotnull AND NOT a.attisdropped
    ) THEN
        RAISE EXCEPTION 'Expected vehicles integer primary key missing';
    END IF;
END
$preflight$;

CREATE TABLE public.vehicle_manufacturers (
    id integer GENERATED BY DEFAULT AS IDENTITY
        (SEQUENCE NAME public.vehicle_manufacturers_id_seq),
    name_he text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT vehicle_manufacturers_pkey PRIMARY KEY (id),
    CONSTRAINT vehicle_manufacturers_name_he_key UNIQUE (name_he),
    CONSTRAINT vehicle_manufacturers_name_he_check CHECK (name_he !~ '^[[:space:]]*$'),
    CONSTRAINT vehicle_manufacturers_created_at_check CHECK (isfinite(created_at))
);
ALTER TABLE public.vehicle_manufacturers OWNER TO postgres;
ALTER TABLE public.vehicle_manufacturers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vehicle_manufacturers NO FORCE ROW LEVEL SECURITY;
-- Backend-only ACL model from Vehicle Identity manual migrations; no client policies.
REVOKE ALL PRIVILEGES ON TABLE public.vehicle_manufacturers
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL PRIVILEGES (id,name_he,is_active,created_at) ON TABLE public.vehicle_manufacturers
    FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE, REFERENCES, TRIGGER, TRUNCATE
    ON TABLE public.vehicle_manufacturers TO service_role;
REVOKE ALL PRIVILEGES ON SEQUENCE public.vehicle_manufacturers_id_seq
    FROM PUBLIC, anon, authenticated, service_role;
GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.vehicle_manufacturers_id_seq TO service_role;

ALTER TABLE public.vehicles
    ADD COLUMN category text,
    ADD COLUMN manufacturer_id integer,
    ADD COLUMN model text,
    ADD COLUMN license_plate text,
    ADD CONSTRAINT vehicles_category_check
        CHECK (category IN ('hatchback','sedan','crossover','minivan','suv')),
    ADD CONSTRAINT vehicles_model_check CHECK (model !~ '^[[:space:]]*$'),
    ADD CONSTRAINT vehicles_license_plate_check CHECK (license_plate !~ '^[[:space:]]*$'),
    ADD CONSTRAINT vehicles_manufacturer_id_fkey FOREIGN KEY (manufacturer_id)
        REFERENCES public.vehicle_manufacturers(id) ON UPDATE NO ACTION ON DELETE RESTRICT;
-- Existing vehicles RLS/ACL, identity, lifecycle and rows are unchanged.
-- NULL metadata remains valid. No plate normalization, uniqueness or new index.

